/** A description of at most about 160 characters: the text's first sentence, or its start. */
function metaDescription(text) {
  const plain = (text ?? '').replace(/\s+/g, ' ').trim()
  const sentence = plain.match(/^.+?(?<!\b(?:e\.g|i\.e|et al|vs|cf))[.!?](?=\s|$)/)?.[0] ?? plain
  if (sentence.length <= 160) return sentence
  return `${sentence.slice(0, 159).replace(/\s+\S*$/, '')}…`
}

