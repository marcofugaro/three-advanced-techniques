for (const technique of techniqueOrder) {
  const folder = folderOfTechnique.get(technique)
  const readme = loadReadme(folder)
  const ids = mains.filter((main) => main.technique === technique).map((main) => main.id)
  if (!readme) warn(`${folder}: no README.md`)
  const tokens = readme?.tokens ?? []
  const firstParagraph = tokens.find((t) => t.type === 'paragraph')
  // The technique's own Usage section, else the first one, under a module's section.
  const usages = readme ? headings(tokens).filter((h) => /^usage$/i.test(h.text)) : []
  const usage = usages.find((h) => !h.ancestors.some((a) => ids.includes(a))) ?? usages[0]
  techniques[technique] = {
    id: technique,
    category: folder.split('/')[0],
    title: titleByFolder.get(folder) ?? titleCase(readme?.h1 ?? technique),
    folder,
    summary: firstParagraph ? plainText(firstParagraph.text) : '',
    readme: readme ? renderTokens(tokens, folder) : '',
    usage: usage ? renderTokens(sectionTokens(tokens, usage.index), folder) : '',
    modules: ids,
  }
  for (const main of mains.filter((m) => m.technique === technique)) {
    const { declarations, header } = parseTypes(main.types)
    const parts = headerParts(header)
    const prose = header.filter((b) => !b.code).map((b) => b.text)
    const snippet = header
      .filter((b) => b.code)
      .map((b) => b.text)
      .join('\n\n')
    const section = readme && headings(tokens).find((h) => h.text === main.id)
    if (!section && ids.length > 1) warn(`${main.id}: no "${main.id}" section in ${folder}/README.md`)
    if (!prose.length) warn(`${main.types}: no header comment`)
    if (!snippet) warn(`${main.types}: no usage snippet in its header`)
    const values = declarations.filter((d) => d.kind !== 'type' && d.kind !== 'interface').map((d) => d.name)
    values.sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }) || a.localeCompare(b))

    const declared = new Set(values)
    const implemented = jsExports(main.source)
    const untyped = [...implemented].filter((name) => !declared.has(name))
    const unimplemented = values.filter((name) => !implemented.has(name))
    if (untyped.length) warn(`${main.source}: exports missing from its .d.ts: ${untyped.join(', ')}`)
    if (unimplemented.length)
      warn(`${main.types}: declares values its module doesn't export: ${unimplemented.join(', ')}`)

    modules[main.id] = {
      id: main.id,
      technique,
      category: main.category,
      source: main.source,
      types: main.types,
      summary: prose.length ? firstSentence(prose[0]) : '',
      intro: parts.intro,
      usage: parts.usage,
      outro: parts.outro,
      guide: section ? renderTokens(sectionTokens(tokens, section.index), folder) : '',
      import: `import { ${values.join(', ')} } from '${pkg.name}'`,
      declarations,
      usedIn: [],
    }
  }
}

