/** A route's page: the shell with the route's base, title and description. */
function routePage(route) {
  let html = shell
  const swap = (pattern, replacement) => {
    if (!pattern.test(html)) throw new Error(`${SHELL}: no ${pattern} to fill in`)
    html = html.replace(pattern, replacement)
  }
  swap(/<base href="[^"]*" \/>/, `<base href="${'../'.repeat(route.path.split('/').filter(Boolean).length)}" />`)
  swap(/<title>[^<]*<\/title>/, `<title>${escapeHtml(route.title)}</title>`)
  swap(/(<meta\s+name="description"\s+content=")[^"]*(")/, `$1${escapeHtml(metaDescription(route.description))}$2`)
  return `${ROUTE_MARK}\n${html}`
}

