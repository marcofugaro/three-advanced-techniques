const printer = ts.createPrinter({ removeComments: true })

/** A type node as one line of text. */
function typeText(node, sf) {
  if (!node) return null
  return printer
    .printNode(ts.EmitHint.Unspecified, node, sf)
    .replace(/\s+/g, ' ')
    .replace(/;\s*}/g, ' }')
    .replace(/\[\s+/g, '[')
    .replace(/\s+\]/g, ']')
    .trim()
}

const typeParams = (node, sf) =>
  node.typeParameters?.length ? `<${node.typeParameters.map((tp) => typeText(tp, sf)).join(', ')}>` : ''

const paramList = (params) =>
  params
    .map((p) => `${p.name}${p.optional && !p.name.startsWith('...') ? '?' : ''}${p.type ? `: ${p.type}` : ''}`)
    .join(', ')

/** A JSDoc block's description and tags; types in braces are read for JS files. */
function parseJsDoc(raw) {
  const doc = { description: '', params: new Map(), returns: null }
  if (!raw) return doc
  const lines = raw
    .replace(/^\/\*\*/, '')
    .replace(/\*\/$/, '')
    .split('\n')
    .map((line) => line.replace(/^\s*\* ?/, '').replace(/\s+$/, ''))
  const blocks = [{ tag: null, lines: [] }]
  for (const line of lines) {
    const tag = line.match(/^\s*@(\w+)\s?(.*)$/)
    if (tag) blocks.push({ tag: tag[1], lines: [tag[2]] })
    else blocks.at(-1).lines.push(line)
  }
  // Wrapped lines join into their paragraph.
  doc.description = blocks[0].lines
    .join('\n')
    .trim()
    .split(/\n\s*\n/)
    .map((paragraph) =>
      paragraph
        .split('\n')
        .map((l) => l.trim())
        .join(' '),
    )
    .join('\n\n')
  for (const { tag, lines } of blocks.slice(1)) {
    let text = lines
      .map((l) => l.trim())
      .join(' ')
      .trim()
    let type = null
    if (text.startsWith('{')) [type, text] = takeBraced(text)
    if (tag === 'param') {
      const param = text.match(/^(\[?)([\w.$]+)(?:=([^\]]*))?\]?\s*(?:-\s+)?([^]*)$/)
      if (param) {
        const [, bracket, name, value, rest] = param
        doc.params.set(name, { name, type, optional: bracket === '[', default: value ?? null, text: rest.trim() })
      }
    } else if (tag === 'returns' || tag === 'return') doc.returns = { type, text }
  }
  return doc
}

/** '{a {b}} rest' → ['a {b}', 'rest']. */
function takeBraced(text) {
  let depth = 0
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '{') depth++
    else if (text[i] === '}' && --depth === 0) {
      return [text.slice(1, i).replace(/\s+/g, ' ').trim(), text.slice(i + 1).trim()]
    }
  }
  return [null, text]
}

function jsDocOf(node, sf) {
  const block = node.jsDoc?.at(-1)
  return parseJsDoc(block ? sf.text.slice(block.pos, block.end) : null)
}

/** `a | b | (c & d)` → ['a', 'b', '(c & d)'], at the top level only. */
function splitUnion(type) {
  const parts = []
  let depth = 0
  let start = 0
  let quote = null
  for (let i = 0; i < type.length; i++) {
    const c = type[i]
    if (quote) {
      if (c === quote) quote = null
    } else if (c === "'" || c === '"' || c === '`') quote = c
    else if ('<([{'.includes(c)) depth++
    else if (')]}'.includes(c) || (c === '>' && type[i - 1] !== '=')) depth--
    else if (c === '|' && depth === 0) {
      parts.push(type.slice(start, i).trim())
      start = i + 1
    }
  }
  parts.push(type.slice(start).trim())
  return parts.filter(Boolean)
}

function paramsOf(parameters, sf, doc) {
  return parameters.map((p) => {
    const name = p.name.getText(sf)
    return {
      name: `${p.dotDotDotToken ? '...' : ''}${name}`,
      type: typeText(p.type, sf) ?? 'any',
      optional: Boolean(p.questionToken || p.initializer),
      doc: docHtml(doc.params.get(name)?.text),
    }
  })
}

/** Overloads as one entry: every parameter by name, typed as the union of its overloads' types. */
function mergeOverloads(nodes, sf) {
  const parts = nodes.map((node) => {
    const doc = jsDocOf(node, sf)
    return { doc, params: paramsOf(node.parameters, sf, doc), returns: typeText(node.type, sf) }
  })
  const unique = (values) => [...new Set(values.filter(Boolean))]
  const names = unique(parts.flatMap((part) => part.params.map((p) => p.name)))
  const params = names.map((name) => {
    const all = parts.map((part) => part.params.find((p) => p.name === name))
    const present = all.filter(Boolean)
    const types = unique(present.flatMap((p) => splitUnion(p.type)))
    const empty = types.filter((t) => t === 'null' || t === 'undefined')
    return {
      name,
      type: [...types.filter((t) => !empty.includes(t)), ...empty].join(' | '),
      optional: all.some((p) => !p || p.optional),
      doc: unique(present.map((p) => p.doc)).join(''),
    }
  })
  return {
    parts,
    params,
    description: unique(parts.map((part) => part.doc.description)).join('\n\n'),
    returns: unique(parts.map((part) => part.returns)).join(' | ') || null,
  }
}

const modifierKinds = (node) => new Set((ts.canHaveModifiers(node) ? ts.getModifiers(node) : null)?.map((m) => m.kind))

function membersOf(nodes, sf, where) {
  const members = []
  const accessors = new Map()
  const methods = new Map()
  for (const node of nodes) {
    if (ts.isConstructorDeclaration(node) || ts.isClassStaticBlockDeclaration?.(node)) continue
    if (!node.name) {
      warn(`${where}: skipped a ${ts.SyntaxKind[node.kind]}`)
      continue
    }
    if (ts.isPrivateIdentifier(node.name)) continue
    const name = node.name.getText(sf)
    const mods = modifierKinds(node)
    if (name.startsWith('_') || mods.has(ts.SyntaxKind.PrivateKeyword) || mods.has(ts.SyntaxKind.ProtectedKeyword))
      continue
    const isStatic = mods.has(ts.SyntaxKind.StaticKeyword)
    const key = `${isStatic ? 'static ' : ''}${name}`
    const prefix = isStatic ? 'static ' : ''

    if (ts.isPropertyDeclaration(node) || ts.isPropertySignature(node)) {
      const doc = jsDocOf(node, sf)
      const readonly = mods.has(ts.SyntaxKind.ReadonlyKeyword)
      const optional = Boolean(node.questionToken)
      const type = typeText(node.type, sf) ?? 'any'
      members.push({
        kind: 'property',
        name,
        type,
        setterType: null,
        readonly,
        optional,
        static: isStatic,
        params: [],
        signature: `${prefix}${readonly ? 'readonly ' : ''}${name}${optional ? '?' : ''}: ${type}`,
        doc: docHtml(doc.description),
        default: parseDefault(doc.description),
      })
    } else if (ts.isGetAccessorDeclaration(node) || ts.isSetAccessorDeclaration(node)) {
      let accessor = accessors.get(key)
      if (!accessor) {
        accessor = { member: { kind: 'property', name, static: isStatic, params: [] }, description: '' }
        accessors.set(key, accessor)
        members.push(accessor.member)
      }
      const doc = jsDocOf(node, sf)
      accessor.description ||= doc.description
      if (ts.isGetAccessorDeclaration(node)) accessor.get = typeText(node.type, sf) ?? 'any'
      else accessor.set = typeText(node.parameters[0]?.type, sf) ?? 'any'
    } else if (ts.isMethodDeclaration(node) || ts.isMethodSignature(node)) {
      let method = methods.get(key)
      if (!method) {
        method = { member: { kind: 'method', name, static: isStatic }, nodes: [] }
        methods.set(key, method)
        members.push(method.member)
      }
      method.nodes.push(node)
    } else warn(`${where}: skipped member ${name} (${ts.SyntaxKind[node.kind]})`)
  }

  for (const { member, get, set, description } of accessors.values()) {
    const prefix = member.static ? 'static ' : ''
    Object.assign(member, {
      type: get ?? set,
      setterType: get && set && set !== get ? set : null,
      readonly: get !== undefined && set === undefined,
      optional: false,
      signature:
        get !== undefined
          ? `${prefix}${set === undefined ? 'readonly ' : ''}${member.name}: ${get}`
          : `${prefix}set ${member.name}(value: ${set})`,
      doc: docHtml(description),
      default: parseDefault(description),
    })
    reorder(member)
  }
  for (const { member, nodes } of methods.values()) {
    const merged = mergeOverloads(nodes, sf)
    const optional = nodes.some((node) => node.questionToken)
    const prefix = member.static ? 'static ' : ''
    Object.assign(member, {
      type: merged.returns,
      setterType: null,
      readonly: false,
      optional,
      params: merged.params,
      signature: nodes
        .map((node, i) => {
          const { params, returns } = merged.parts[i]
          return `${prefix}${member.name}${optional ? '?' : ''}${typeParams(node, sf)}(${paramList(params)}): ${returns}`
        })
        .join('\n'),
      doc: docHtml(merged.description),
      default: null,
    })
    reorder(member)
  }
  return members
}

/** Rewrites a member's keys in the contract's order. */
function reorder(member) {
  const order = ['kind', 'name', 'type', 'setterType', 'readonly', 'optional', 'static', 'params', 'signature', 'doc']
  const copy = { ...member }
  for (const key of Object.keys(member)) delete member[key]
  for (const key of [...order, 'default']) member[key] = copy[key]
}

const declaration = (fields) => ({
  kind: fields.kind,
  name: fields.name,
  doc: fields.doc ?? '',
  signature: fields.signature,
  extends: fields.extends ?? null,
  params: fields.params ?? [],
  returns: fields.returns ?? null,
  // Own key only: every object inherits a `constructor`.
  constructor: Object.hasOwn(fields, 'constructor') ? fields.constructor : null,
  members: fields.members ?? [],
  type: fields.type ?? null,
})

function classDeclaration(node, sf, where) {
  const name = node.name.text
  const doc = jsDocOf(node, sf)
  const heritage = node.heritageClauses?.find((h) => h.token === ts.SyntaxKind.ExtendsKeyword)
  const base = heritage ? heritage.types.map((t) => typeText(t, sf)).join(', ') : null
  // A private constructor: instances come from elsewhere, as SlicedPMREMJob's.
  const constructors = node.members.filter(
    (m) => ts.isConstructorDeclaration(m) && !modifierKinds(m).has(ts.SyntaxKind.PrivateKeyword),
  )
  let constructor = null
  if (constructors.length) {
    const merged = mergeOverloads(constructors, sf)
    constructor = {
      signature: merged.parts.map((part) => `new ${name}(${paramList(part.params)})`).join('\n'),
      params: merged.params,
      doc: docHtml(merged.description),
    }
  }
  return declaration({
    kind: 'class',
    name,
    doc: docHtml(doc.description),
    signature: `class ${name}${typeParams(node, sf)}${base ? ` extends ${base}` : ''}`,
    extends: base,
    constructor,
    members: membersOf(node.members, sf, `${where} ${name}`),
  })
}

function functionDeclaration(nodes, sf) {
  const name = nodes[0].name.text
  const merged = mergeOverloads(nodes, sf)
  return declaration({
    kind: 'function',
    name,
    doc: docHtml(merged.description),
    signature: nodes
      .map((node, i) => {
        const { params, returns } = merged.parts[i]
        return `function ${name}${typeParams(node, sf)}(${paramList(params)}): ${returns}`
      })
      .join('\n'),
    params: merged.params,
    returns: merged.returns,
  })
}

function interfaceDeclaration(node, sf, where) {
  const name = node.name.text
  const heritage = node.heritageClauses?.find((h) => h.token === ts.SyntaxKind.ExtendsKeyword)
  const base = heritage ? heritage.types.map((t) => typeText(t, sf)).join(', ') : null
  return declaration({
    kind: 'interface',
    name,
    doc: docHtml(jsDocOf(node, sf).description),
    signature: `interface ${name}${typeParams(node, sf)}${base ? ` extends ${base}` : ''}`,
    extends: base,
    members: membersOf(node.members, sf, `${where} ${name}`),
  })
}

function typeAliasDeclaration(node, sf, where) {
  const name = node.name.text
  const doc = jsDocOf(node, sf)
  const type = typeText(node.type, sf)
  const fn = ts.isFunctionTypeNode(node.type)
  return declaration({
    kind: 'type',
    name,
    doc: docHtml(doc.description),
    signature: `type ${name}${typeParams(node, sf)} = ${type}`,
    params: fn ? paramsOf(node.type.parameters, sf, doc) : [],
    returns: fn ? typeText(node.type.type, sf) : null,
    members: ts.isTypeLiteralNode(node.type) ? membersOf(node.type.members, sf, `${where} ${name}`) : [],
    type,
  })
}

/** A const typed as a function, such as a node's factory, reads as a function. */
function variableDeclaration(node, statement, sf, where) {
  const name = node.name.getText(sf)
  const doc = jsDocOf(statement, sf)
  const typeNode = node.type
  const type = typeText(typeNode, sf) ?? 'any'
  if (typeNode && ts.isFunctionTypeNode(typeNode)) {
    const params = paramsOf(typeNode.parameters, sf, doc)
    const returns = typeText(typeNode.type, sf)
    return declaration({
      kind: 'function',
      name,
      doc: docHtml(doc.description),
      signature: `function ${name}${typeParams(typeNode, sf)}(${paramList(params)}): ${returns}`,
      params,
      returns,
      type,
    })
  }
  return declaration({
    kind: 'const',
    name,
    doc: docHtml(doc.description),
    signature: `const ${name}: ${type}`,
    members: typeNode && ts.isTypeLiteralNode(typeNode) ? membersOf(typeNode.members, sf, `${where} ${name}`) : [],
    type,
  })
}

function enumDeclaration(node, sf) {
  const name = node.name.text
  return declaration({
    kind: 'enum',
    name,
    doc: docHtml(jsDocOf(node, sf).description),
    signature: `enum ${name}`,
    members: node.members.map((member) => {
      const doc = jsDocOf(member, sf)
      const value = member.initializer?.getText(sf) ?? null
      return {
        kind: 'property',
        name: member.name.getText(sf),
        type: value,
        setterType: null,
        readonly: true,
        optional: false,
        static: false,
        params: [],
        signature: `${member.name.getText(sf)}${value ? ` = ${value}` : ''}`,
        doc: docHtml(doc.description),
        default: null,
      }
    }),
  })
}

/** A .d.ts's exported declarations in file order, its default export left out, and its header comment. */
function parseTypes(path) {
  const sf = ts.createSourceFile(path, read(path), ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
  const declarations = []
  const byName = new Map()
  const exported = new Set()
  const functions = new Map()
  for (const statement of sf.statements) {
    if (
      ts.isFunctionDeclaration(statement) &&
      statement.name &&
      modifierKinds(statement).has(ts.SyntaxKind.ExportKeyword)
    ) {
      const list = functions.get(statement.name.text) ?? []
      list.push(statement)
      functions.set(statement.name.text, list)
    }
  }
  const add = (decl) => {
    const existing = byName.get(decl.name)
    if (!existing) {
      byName.set(decl.name, decl)
      declarations.push(decl)
      return
    }
    // A type beside a value of the same name, as `WormState`: one entry, the value's.
    const [value, other] = decl.kind === 'type' ? [existing, decl] : [decl, existing]
    value.doc = [value.doc, other.doc, `<p><code>${escapeHtml(other.signature)}</code></p>`].filter(Boolean).join('')
    if (value !== existing) declarations.splice(declarations.indexOf(existing), 1, value)
    byName.set(decl.name, value)
  }
  for (const statement of sf.statements) {
    if (ts.isImportDeclaration(statement) || ts.isExportAssignment(statement)) continue
    if (ts.isExportDeclaration(statement)) {
      warn(`${path}: skipped \`${statement.getText(sf).split('\n')[0]}\``)
      continue
    }
    const mods = modifierKinds(statement)
    if (!mods.has(ts.SyntaxKind.ExportKeyword) || mods.has(ts.SyntaxKind.DefaultKeyword)) continue
    if (ts.isVariableStatement(statement)) {
      for (const node of statement.declarationList.declarations) {
        exported.add(node.name.getText(sf))
        add(variableDeclaration(node, statement, sf, path))
      }
      continue
    }
    const name = statement.name?.text
    if (name) exported.add(name)
    if (ts.isClassDeclaration(statement)) add(classDeclaration(statement, sf, path))
    else if (ts.isFunctionDeclaration(statement)) {
      if (functions.get(name)?.[0] === statement) add(functionDeclaration(functions.get(name), sf))
    } else if (ts.isInterfaceDeclaration(statement)) add(interfaceDeclaration(statement, sf, path))
    else if (ts.isTypeAliasDeclaration(statement)) add(typeAliasDeclaration(statement, sf, path))
    else if (ts.isEnumDeclaration(statement)) add(enumDeclaration(statement, sf))
    else warn(`${path}: skipped export ${name ?? ts.SyntaxKind[statement.kind]}`)
  }

  // A factory's parameters read their docs from the constructor of the class it returns.
  for (const decl of declarations) {
    const made = decl.kind === 'function' && byName.get(decl.returns?.match(/^\w+/)?.[0])
    if (made?.kind !== 'class' || !made.constructor) continue
    // By name, else by position: bloom(node) documents BloomNode's inputNode
    for (const [i, param] of decl.params.entries()) {
      param.doc ||= (made.constructor.params.find((p) => p.name === param.name) ?? made.constructor.params[i])?.doc ?? ''
    }
  }

  const missing = [...exported].filter((name) => !byName.has(name))
  if (missing.length) warn(`${path}: exports missing from the docs: ${missing.join(', ')}`)
  return { declarations, header: headerOf(sf) }
}

/** The leading `//` comment block: prose paragraphs and the indented usage snippet. */
function headerOf(sf) {
  const lines = []
  for (const range of ts.getLeadingCommentRanges(sf.text, 0) ?? []) {
    if (range.kind !== ts.SyntaxKind.SingleLineCommentTrivia) break
    lines.push(sf.text.slice(range.pos + 2, range.end).replace(/\s+$/, ''))
  }
  return splitHeader(lines, 3)
}

/**
 * A header's blocks in source order: the prose before the first snippet, the snippets with any prose between them,
 * and the prose after the last.
 */
function headerParts(blocks) {
  const prose = (list) => docHtml(list.map((b) => b.text).join('\n\n'))
  const first = blocks.findIndex((b) => b.code)
  if (first === -1) return { intro: prose(blocks), usage: '', outro: '' }
  const last = blocks.findLastIndex((b) => b.code)
  return {
    intro: prose(blocks.slice(0, first)),
    usage: blocks
      .slice(first, last + 1)
      .map((b) => (b.code ? highlight(b.text) : docHtml(b.text)))
      .join(''),
    outro: prose(blocks.slice(last + 1)),
  }
}

/**
 * Comment lines (without their `//` or `*`) as prose paragraphs and code blocks: a line indented by at least
 * `indent` spaces is code, and blank lines between code lines stay in its block.
 */
function splitHeader(lines, indent) {
  const blocks = []
  let pendingBlank = false
  for (const line of lines) {
    if (!line.trim()) {
      pendingBlank = true
      continue
    }
    const isCode = line.match(/^ */)[0].length >= indent
    const last = blocks.at(-1)
    if (last && last.code === isCode && (isCode || !pendingBlank)) {
      if (pendingBlank) last.lines.push('')
      last.lines.push(line)
    } else blocks.push({ code: isCode, lines: [line] })
    pendingBlank = false
  }
  for (const block of blocks) {
    if (block.code) {
      const min = Math.min(...block.lines.filter(Boolean).map((l) => l.match(/^ */)[0].length))
      block.text = block.lines.map((l) => l.slice(min)).join('\n')
    } else block.text = block.lines.map((l) => l.trim()).join(' ')
  }
  return blocks
}

// The utility module, read from its JSDoc

function parseUtility({ id, module, title, source }) {
  const file = join(root, source)
  const program = ts.createProgram([file], {
    allowJs: true,
    noEmit: true,
    target: ts.ScriptTarget.ESNext,
    module: ts.ModuleKind.ESNext,
    lib: ['lib.esnext.d.ts', 'lib.dom.d.ts'],
    types: [],
  })
  const checker = program.getTypeChecker()
  const sf = program.getSourceFile(file)
  const typeString = (type) =>
    checker.typeToString(type, undefined, ts.TypeFormatFlags.UseSingleQuotesForStringLiteralType)

  const node = sf.statements.find((s) => ts.isClassDeclaration(s) && s.name?.text === module)
  if (!node || !jsExports(source).has(module)) throw new Error(`no exported class ${module}`)

  // The header: prose, the usage snippet, and an "Options and properties:" list of `name - doc` entries.
  const range = ts.getLeadingCommentRanges(sf.text, 0)?.find((r) => sf.text.startsWith('/**', r.pos))
  const headerLines = sf.text
    .slice(range.pos + 3, range.end - 2)
    .split('\n')
    .map((line) => line.replace(/^\s*\* ?/, '').replace(/\s+$/, ''))
  const blocks = splitHeader(headerLines, 2)
  const optionDocs = new Map()
  const listAt = blocks.findIndex((b) => !b.code && /Options and properties:$/.test(b.text))
  if (listAt !== -1 && blocks[listAt + 1]?.code) {
    let current = null
    for (const line of blocks[listAt + 1].lines) {
      const entry = line.match(/^\s*(\w+) - (.*)$/)
      if (entry) optionDocs.set((current = entry[1]), entry[2])
      else if (current) optionDocs.set(current, `${optionDocs.get(current)} ${line.trim()}`)
    }
    blocks.splice(listAt, 2)
  }
  // Each entry reads as a sentence, but a unit or a name it opens with: 'ms: …', 'deviceMemory ≤ 4 GB …'
  for (const [name, text] of optionDocs) {
    if (!/^(ms|px|s)\b|^[a-z]+[A-Z]/.test(text)) optionDocs.set(name, text.replace(/^[a-z]/, (c) => c.toUpperCase()))
  }
  const opening = blocks.find((b) => !b.code)
  opening.text = opening.text.replace(new RegExp(`^${module}\\s+-\\s+`), '').replace(/^[a-z]/, (c) => c.toUpperCase())
  const prose = blocks.filter((b) => !b.code).map((b) => b.text)
  const snippet = blocks
    .filter((b) => b.code)
    .map((b) => b.text)
    .join('\n\n')
  const parts = headerParts(blocks)

  // The constructor's JSDoc types the options; properties of the same name share them.
  const ctorNode = node.members.find(ts.isConstructorDeclaration)
  const ctorDoc = jsDocOf(ctorNode, sf)
  const optionTypes = new Map()
  for (const [name, param] of ctorDoc.params) optionTypes.set(name.replace(/^options\./, ''), param.type)
  // An untagged parameter takes the type a same-named one is tagged with elsewhere in the class.
  const taggedTypes = new Map()
  for (const member of node.members) {
    for (const [name, param] of jsDocOf(member, sf).params)
      if (param.type && !taggedTypes.has(name)) taggedTypes.set(name, param.type)
  }
  const inferredType = (p) => {
    const type = typeString(checker.getTypeAtLocation(p))
    return ['null', 'undefined', '{}'].includes(type) ? 'object' : type
  }
  const jsParams = (fn, doc) =>
    fn.parameters.map((p) => {
      const name = p.name.getText(sf)
      const tag = doc.params.get(name)
      return {
        name,
        type: tag?.type ?? taggedTypes.get(name) ?? inferredType(p),
        optional: Boolean(p.initializer || p.questionToken || tag?.optional),
        doc: docHtml(tag?.text),
      }
    })
  const ctorParams = jsParams(ctorNode, ctorDoc)
  const options = ctorParams.find((p) => p.name === 'options')
  if (options) {
    const fields = [...ctorDoc.params.values()].filter((p) => p.name.startsWith('options.'))
    options.type = `{ ${fields.map((p) => `${p.name.slice(8)}?: ${p.type ?? 'any'}`).join('; ')} }`
  }

  const members = []
  for (const member of node.members) {
    if (!member.name || ts.isPrivateIdentifier(member.name) || ts.isConstructorDeclaration(member)) continue
    const name = member.name.getText(sf)
    if (name.startsWith('_')) continue
    const isStatic = modifierKinds(member).has(ts.SyntaxKind.StaticKeyword)
    const prefix = isStatic ? 'static ' : ''
    if (ts.isPropertyDeclaration(member)) {
      const brand = name === 'type' || name === `is${module}`
      const literal = member.initializer && /^(true|false|-?[\d.]+|'[^']*')$/.test(member.initializer.getText(sf))
      const type =
        name === `is${module}`
          ? 'true'
          : member.initializer
            ? typeString(checker.getBaseTypeOfLiteralType(checker.getTypeAtLocation(member.name)))
            : (optionTypes.get(name) ?? 'any')
      const text = optionDocs.get(name) ?? ''
      members.push({
        kind: 'property',
        name,
        type,
        setterType: null,
        readonly: brand,
        optional: false,
        static: isStatic,
        params: [],
        signature: `${prefix}${brand ? 'readonly ' : ''}${name}: ${type}`,
        doc: docHtml(text),
        default: brand ? null : literal ? member.initializer.getText(sf) : parseDefault(text),
      })
    } else if (ts.isMethodDeclaration(member)) {
      const doc = jsDocOf(member, sf)
      const params = jsParams(member, doc)
      let returns = doc.returns?.type
      if (!returns) {
        const inferred = typeString(checker.getReturnTypeOfSignature(checker.getSignatureFromDeclaration(member)))
        const async = modifierKinds(member).has(ts.SyntaxKind.AsyncKeyword)
        returns = inferred.length <= 60 ? inferred : async ? 'Promise<object>' : 'object'
      }
      members.push({
        kind: 'method',
        name,
        type: returns,
        setterType: null,
        readonly: false,
        optional: false,
        static: isStatic,
        params,
        signature: `${prefix}${name}(${paramList(params)}): ${returns}`,
        doc: docHtml(doc.description),
        default: null,
      })
    }
  }

  const classDecl = declaration({
    kind: 'class',
    name: module,
    doc: docHtml(jsDocOf(node, sf).description),
    signature: `class ${module}`,
    constructor: {
      signature: `new ${module}(${paramList(ctorParams)})`,
      params: ctorParams,
      doc: docHtml(ctorDoc.description),
    },
    members,
  })
  const optionsList = [...optionDocs].map(([name, text]) => `- \`${name}\`: ${text}`).join('\n')
  const readme = [
    ...blocks.map((b) => (b.code ? `\`\`\`js\n${b.text}\n\`\`\`` : b.text)),
    optionsList && `## Options and properties\n\n${optionsList}`,
  ]
    .filter(Boolean)
    .join('\n\n')
  return {
    technique: { id, title, folder: posix.dirname(source), summary: firstSentence(prose[0]), readme: docHtml(readme) },
    module: {
      id: module,
      source,
      summary: firstSentence(prose[0]),
      intro: parts.intro,
      usage: parts.usage,
      outro: parts.outro,
      snippet: snippet ? highlight(snippet) : '',
      import: `import { ${module} } from '${pkg.name}/${source}'`,
      declarations: [classDecl],
    },
  }
}

// Exports of the JS modules, to check the .d.ts against

function jsExports(path) {
  const sf = ts.createSourceFile(path, read(path), ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
  const names = new Set()
  for (const statement of sf.statements) {
    if (ts.isExportDeclaration(statement)) {
      if (statement.exportClause && ts.isNamedExports(statement.exportClause)) {
        for (const element of statement.exportClause.elements) names.add(element.name.text)
      }
      continue
    }
    const mods = modifierKinds(statement)
    if (!mods.has(ts.SyntaxKind.ExportKeyword) || mods.has(ts.SyntaxKind.DefaultKeyword)) continue
    if (ts.isVariableStatement(statement)) {
      for (const d of statement.declarationList.declarations) names.add(d.name.getText(sf))
    } else if (statement.name) names.add(statement.name.text)
  }
  return names
}

// Pages → modules

/** The main modules a page reaches through its own scripts, recursively through local non-main ones. */
function modulesOfPage(page, mainPaths) {
  const found = new Set()
  const visited = new Set()
  const visit = (code, from) => {
    for (const { fileName } of ts.preProcessFile(code, true, true).importedFiles) {
      if (!/^\.{0,2}\//.test(fileName)) continue // bare specifiers: packages
      const path = fileName.startsWith('/')
        ? fileName.slice(1)
        : posix.normalize(posix.join(posix.dirname(from), fileName))
      walk(path)
    }
  }
  const walk = (path) => {
    if (mainPaths.has(path)) return void found.add(mainPaths.get(path))
    if (visited.has(path) || !path.endsWith('.js') || !exists(path)) return
    visited.add(path)
    visit(read(path), path)
  }
  const html = read(page.path)
  for (const [, attrs, body] of html.matchAll(/<script\b([^>]*)>([^]*?)<\/script>/gi)) {
    const type = attrs.match(/\btype\s*=\s*["']?([^"'\s>]+)/i)?.[1]
    const src = attrs.match(/\bsrc\s*=\s*["']([^"']+)["']/i)?.[1]
    if (type === 'importmap') continue
    if (src) {
      if (!/^([a-z]+:)?\/\//i.test(src)) walk(posix.normalize(posix.join(page.folder, src.split(/[?#]/)[0])))
    } else if (type === 'module') visit(body, page.path)
  }
  return found
}

