/** A repo path's place in the site; a live link (`live`) leads to its example, or nowhere. */
function localTarget(path, live = false) {
  const [rest, anchor = ''] = path.split('#')
  let file = posix.normalize(rest.split('?')[0] || '.').replace(/\/+$/, '')
  if (file === '.') file = ''
  const page = pageByPath.get(file) ?? pageByPath.get(file ? `${file}/index.html` : 'index.html')
  if (live) return page ? { href: `examples/${page.id}/` } : null
  if (file === '' || file === 'README.md') return { href: 'docs/' }
  const folder = file.endsWith('/README.md') ? posix.dirname(file) : file
  const technique = [...folderOfTechnique].find(([, f]) => f === folder)?.[0]
  if (technique) {
    const module = anchor && mains.find((main) => main.technique === technique && slug(main.id) === slug(anchor))
    if (module) return { href: `docs/${module.id}/` }
    return { href: `docs/${technique}/${anchor ? `#${headingId(anchor)}` : ''}` }
  }
  if (moduleByPath.has(file)) return { href: `docs/${moduleByPath.get(file)}/` }
  if (file.endsWith('.html') && page) return { href: `examples/${page.id}/` }
  // Images load from the site; any other file reads best on GitHub (Pages serves .js raw and turns .md into .html)
  if (ASSET.test(file)) return { href: `${REPO_ROOT}${file}` }
  return { href: `${REPO}/blob/main/${file}${anchor ? `#${anchor}` : ''}`, external: true }
}

