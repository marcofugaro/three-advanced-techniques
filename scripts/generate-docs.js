/** The first sentence of a paragraph, as plain text; a closing colon becomes a full stop. */
function firstSentence(markdown) {
  const text = plainText(markdown)
  const match = text.match(/^.+?(?<!\b(?:e\.g|i\.e|et al|vs|cf))[.:!?](?=\s|$)/)
  return (match ? match[0] : text).replace(/:$/, '.')
}

/** The value of a doc's "Default …." sentence: "Default 0.5." → '0.5', "Default null: none." → 'null'. */
function parseDefault(text) {
  const match = text?.match(/(?:^|[.!?]\s+)Default(:?)\s+([^]*?)\.(?=\s|$)/)
  if (!match) return null
  let value = match[2].replace(/`/g, '').replace(/\s+/g, ' ').trim()
  const short = !match[1] && value.match(/^(\S+):\s/)
  if (short) value = short[1]
  return value
}

